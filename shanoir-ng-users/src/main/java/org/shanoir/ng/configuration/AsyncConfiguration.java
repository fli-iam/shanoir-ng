package org.shanoir.ng.configuration;

import java.util.concurrent.Executor;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.scheduling.annotation.EnableAsync;
import org.springframework.scheduling.concurrent.ThreadPoolTaskExecutor;

/**
 * Asynchronous execution configuration. Mass emails are sent on a dedicated
 * single thread so the HTTP request returns immediately and the SMTP server
 * is never hit by more than one campaign at a time.
 *
 * @author afragkiadakis
 */
@Configuration
@EnableAsync
public class AsyncConfiguration {

    @Bean(name = "massEmailExecutor")
    public Executor massEmailExecutor() {
        final ThreadPoolTaskExecutor executor = new ThreadPoolTaskExecutor();
        executor.setCorePoolSize(1);
        executor.setMaxPoolSize(1);
        executor.setQueueCapacity(10);
        executor.setThreadNamePrefix("mass-email-");
        executor.initialize();
        return executor;
    }

}
