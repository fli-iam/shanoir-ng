-- 0068_update_conditions_scopes.sql renamed study_card_condition to card_condition and fixed the FK
-- on study_card_condition_join accordingly, but missed the equivalent FK on quality_card_condition_join
-- (created in 0023_quality_control_modify_study_cards.sql), which is left pointing at the now-renamed
-- study_card_condition table. This causes "Cannot add or update a child row" when saving quality cards.
-- The constraint name is looked up dynamically since it can differ between instances (manually named
-- in 0023, auto-generated by Hibernate on others).
--
-- On instances whose schema was built up via Hibernate ddl-auto instead of running these migrations
-- in order (e.g. some dev databases), the same class of bug shows up on two other columns: the old
-- tables (study_card_condition, quality_examination_rule) never got renamed away, they just sit
-- alongside their replacement (card_condition, quality_card_rule) as empty orphans, each still with
-- its own leftover FK on a join table's column, next to a second, correct FK to the live table. Every
-- insert then fails the unsatisfiable stale FK. All three cases below are fixed the same way: drop the
-- stale FK if present, add the correct one if missing, using a dynamic constraint-name lookup so this
-- stays a no-op wherever the earlier migrations already left things in a clean state.

SET @old_fk := (
    SELECT CONSTRAINT_NAME FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'quality_card_condition_join'
      AND COLUMN_NAME = 'condition_id'
      AND REFERENCED_TABLE_NAME = 'study_card_condition'
    LIMIT 1
);

SET @drop_sql := IF(@old_fk IS NOT NULL,
    CONCAT('ALTER TABLE quality_card_condition_join DROP FOREIGN KEY `', @old_fk, '`'),
    'DO 0');
PREPARE stmt FROM @drop_sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

SET @new_fk := (
    SELECT CONSTRAINT_NAME FROM information_schema.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'quality_card_condition_join'
      AND COLUMN_NAME = 'condition_id'
      AND REFERENCED_TABLE_NAME = 'card_condition'
    LIMIT 1
);

SET @add_sql := IF(@new_fk IS NULL,
    'ALTER TABLE quality_card_condition_join ADD CONSTRAINT FK_qccj_condition_id FOREIGN KEY (condition_id) REFERENCES card_condition(id)',
    'DO 0');
PREPARE stmt FROM @add_sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

-- study_card_condition_join.condition_id: stale FK left pointing at the orphaned study_card_condition
